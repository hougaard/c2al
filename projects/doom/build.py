# Builds DOOM for Business Central: PureDOOM.h -> patch.py -> bc_glue.c -> preprocess -> c2al -> AL codeunit (+ JS test build)
#   python build.py [--unchecked] [--profile]
#   AL_OUT=<path> overrides where the AL codeunit is written
import sys, json, subprocess, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..'))
from c2al.config import Config
from c2al.main import build
from c2al.emit_js import JSEmitter
from c2al.emit_al import ALEmitter

STACK = 256 * 1024

# C entry points the BC page / JS harness call
ENTRY_POINTS = ['bc_doom_init', 'bc_doom_frame', 'bc_tic_lag', 'doom_update', 'doom_force_update', 'doom_key_down', 'doom_key_up',
                'doom_button_down', 'doom_button_up', 'doom_mouse_move', 'bc_get_screen', 'bc_get_palette']

# PureDOOM's own libc wrappers and the fixed point math are replaced by hand written AL
INTRINSICS = {
    'doom_memset': 'Rt_MemSet',
    'doom_memcpy': 'Rt_MemCpy',
    'FixedMul': 'Rt_FixedMul',
    'FixedDiv': 'Rt_FixedDiv',
    'doom_strlen': 'Rt_StrLen',
}


def doom_config():
    return Config(
        entry_points=ENTRY_POINTS,
        runtime_text=open(os.path.join(HERE, 'runtime.al')).read(),
        intrinsics=INTRINSICS,
        native_prefixes=('bc_',),
        reserve_exclude=('bc_', 'doom_'),
        reserve_all_words=True,
        wrap_sites=json.load(open(os.path.join(HERE, 'wrap_sites.json'))),
        error_tag='DOOM')


def main():
    os.chdir(HERE)
    subprocess.check_call([sys.executable, 'patch.py'])
    subprocess.check_call([sys.executable, '-m', 'ziglang', 'cc', '-E', '-m32', '-target', 'x86-windows-gnu',
                           'bc_glue.c', '-o', 'glue.i'])
    cfg = doom_config()
    comp, errors = build('glue.i', cfg)
    if errors:
        for e in errors: print(e)
        sys.exit(1)
    data_end = comp.data_start + len(comp.image)
    stack_top = (data_end + STACK + 15) // 16 * 16
    layout = {'data_start': comp.data_start, 'data_end': data_end, 'stack_top': stack_top, 'heap_start': stack_top + 16}
    os.makedirs('build', exist_ok=True)
    open('build/image.bin', 'wb').write(bytes(comp.image))
    json.dump(layout, open('build/layout.json', 'w'))
    checked = '--unchecked' not in sys.argv
    open('build/doom.js', 'w').write(JSEmitter(comp, checked, '--profile' in sys.argv).emit())
    print('layout', layout)
    layout['memsize'] = (layout['heap_start'] + 4095) // 4096 * 4096
    header = [
        'DOOM for Business Central',
        'This codeunit is PureDOOM (https://github.com/Daivuk/PureDOOM) translated from C to AL.',
        'It is generated by c2al - do not edit by hand.',
        'C memory is emulated by the Mem list (one element per byte), C pointers are indexes into Mem.',
        'DOOM source code (C) 1993-1996 id Software, Inc., released under the GNU GPL v2.',
    ]
    al = ALEmitter(comp, layout, cfg.runtime_text, header).emit(66600, 'DOOM Engine')
    out = os.environ.get('AL_OUT', r'C:/working/youtube2/BCDoom/src/DoomEngine.Codeunit.al')
    open(out, 'w', newline=chr(13) + chr(10)).write(al)
    print('AL lines', al.count(chr(10)), 'bytes', len(al))
    return comp


if __name__ == '__main__':
    main()
