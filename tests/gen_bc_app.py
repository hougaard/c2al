# Builds every example into examples/bc-app/src/generated and writes the AL test runner
# (codeunit "C2AL Example Tests") from the "tests" in each c2al.json - the same tests run_tests.py runs in JS.
#   python tests/gen_bc_app.py
import glob, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from c2al.driver import build_project, entry_names

APP = os.path.join(ROOT, 'examples', 'bc-app')
TESTS_ID = 50100


def al_text(s):
    return "'" + s.replace("'", "''") + "'"


def al_int(v):
    return '(-2147483647 - 1)' if v == -2147483648 else str(v)


def al_arg(a):
    if isinstance(a, int):
        return al_int(a)
    if 'text' in a:
        return 'C.AllocText(%s)' % al_text(a['text'])
    if 'big' in a:
        return "Big('%s')" % a['big']
    raise ValueError(a)


def test_proc(idx, proj, names):
    lines = []
    w = lines.append
    w('    local procedure Example%02d(var Report: TextBuilder; var Passed: Integer; var Failed: Integer)' % idx)
    w('    var')
    w('        C: Codeunit "%s";' % proj.object_name)
    w('        Start: DateTime;')
    w('    begin')
    w("        Report.AppendLine(%s);" % al_text('== ' + proj.name))
    w('        Start := CurrentDateTime();')
    w('        C.Initialize();')
    for t in proj.tests:
        call = 'C.%s(%s)' % (names[t['call']], ', '.join(al_arg(a) for a in t['args']))
        label = al_text('%s(%s)' % (t['call'], ', '.join(json.dumps(a) for a in t['args'])))
        if 'expect_error' in t:
            w('        // %s: expected to raise an error in AL, not run here' % t['call'])
        elif 'expect_log' in t:
            w('        C.ClearLog();')
            w('        %s;' % call)
            w('        Check(Report, Passed, Failed, %s, C.GetLog(), %s);' % (label, al_text(t['expect_log'])))
        elif 'expect' not in t:
            w('        %s;' % call)
        else:
            e = t['expect']
            if isinstance(e, dict) and 'text' in e:
                got, exp = 'C.ReadText(%s)' % call, al_text(e['text'])
            elif isinstance(e, dict) and 'big' in e:
                got, exp = 'Format(%s, 0, 9)' % call, al_text(e['big'])
            else:
                got, exp = 'Format(%s, 0, 9)' % call, al_text(str(e))
            w('        Check(Report, Passed, Failed, %s, %s, %s);' % (label, got, exp))
    w("        Report.AppendLine(StrSubstNo('   %1 ms', CurrentDateTime() - Start));")
    w('    end;')
    return lines


def main():
    projects = []
    for p in sorted(glob.glob(os.path.join(ROOT, 'examples', '*', 'c2al.json'))):
        proj, comp = build_project(p)
        projects.append((proj, entry_names(comp, proj.entry_points)))
    out = ['// Generated by tests/gen_bc_app.py from the "tests" in examples/*/c2al.json - do not edit by hand.',
           'codeunit %d "C2AL Example Tests"' % TESTS_ID, '{',
           '    procedure RunAll(var Passed: Integer; var Failed: Integer): Text',
           '    var', '        Report: TextBuilder;', '    begin']
    for i, _ in enumerate(projects, 1):
        out.append('        Example%02d(Report, Passed, Failed);' % i)
    out += ['        exit(Report.ToText());', '    end;', '']
    for i, (proj, names) in enumerate(projects, 1):
        out += test_proc(i, proj, names) + ['']
    out += [
        '    local procedure Check(var Report: TextBuilder; var Passed: Integer; var Failed: Integer; Name: Text; Actual: Text; Expected: Text)',
        '    begin',
        '        if Actual = Expected then begin',
        '            Passed += 1;',
        "            Report.AppendLine('ok   ' + Name + ' = ' + Actual);",
        '        end else begin',
        '            Failed += 1;',
        "            Report.AppendLine('FAIL ' + Name + ' = ' + Actual + ', expected ' + Expected);",
        '        end;',
        '    end;',
        '',
        '    local procedure Big(Value: Text): BigInteger',
        '    var',
        '        b: BigInteger;',
        '    begin',
        '        Evaluate(b, Value);',
        '        exit(b);',
        '    end;',
        '}']
    path = os.path.join(APP, 'src', 'ExampleTests.Codeunit.al')
    open(path, 'w', newline='\r\n').write('\n'.join(out) + '\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
