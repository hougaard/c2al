# Builds c2al projects and checks the translation three ways:
#   expected   the "expect" / "expect_log" values written in c2al.json
#   js         the translated program (same IR as the AL codeunit) run under node with AL semantics
#   native     the original C compiled natively with zig cc (32 bit), the reference
#
#   python tests/run_tests.py                 all examples
#   python tests/run_tests.py examples/05-crc32 [--no-native] [-v]
import glob, json, os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from c2al.driver import build_project, INCLUDE_DIR


def c_string(s):
    out = '"'
    for ch in s:
        o = ord(ch)
        if ch in '"\\':
            out += '\\' + ch
        elif ch == '\n':
            out += '\\n'
        elif o < 32 or o > 126:
            out += '\\x%02x" "' % o
        else:
            out += ch
    return out + '"'


def c_arg(a):
    if isinstance(a, int):
        return str(a)
    if 'text' in a:
        return 'h_dup(%s)' % c_string(a['text'])
    if 'big' in a:
        return '%sLL' % a['big']
    raise ValueError(a)


def expected_line(t):
    if 'expect_error' in t:
        return None
    if 'expect_log' in t:
        return 'L ' + json.dumps(t['expect_log'])
    if 'expect' not in t:
        return '-'
    e = t['expect']
    if isinstance(e, dict) and 'text' in e:
        return 'R ' + json.dumps(e['text'])
    if isinstance(e, dict) and 'big' in e:
        return 'R ' + e['big']
    return 'R %d' % e


def native_main(proj):
    lines = ['/* generated by tests/run_tests.py: calls the tests natively */']
    for s in proj.sources:
        lines.append('#include "%s"' % os.path.relpath(proj.file(s), proj.build_dir).replace('\\', '/'))
    lines += ['void h_int(int); void h_big(long long); void h_text(const char*); void h_void(void);',
              'void h_log_begin(void); void h_log(void); char* h_dup(const char*);',
              'int main(void)', '{']
    for t in proj.tests:
        call = '%s(%s)' % (t['call'], ', '.join(c_arg(a) for a in t['args']))
        if 'expect_error' in t:
            lines.append('    h_void(); /* %s: expected to fail in AL, not run natively */' % t['call'])
        elif 'expect_log' in t:
            lines.append('    h_log_begin(); %s; h_log();' % call)
        elif 'expect' not in t:
            lines.append('    %s; h_void();' % call)
        elif isinstance(t['expect'], dict) and 'text' in t['expect']:
            lines.append('    h_text(%s);' % call)
        elif isinstance(t['expect'], dict) and 'big' in t['expect']:
            lines.append('    h_big(%s);' % call)
        else:
            lines.append('    h_int(%s);' % call)
    lines += ['    return 0;', '}']
    return '\n'.join(lines) + '\n'


def run_native(proj):
    src = os.path.join(proj.build_dir, 'native_main.c')
    exe = os.path.join(proj.build_dir, 'native.exe')
    open(src, 'w').write(native_main(proj))
    subprocess.check_call([sys.executable, '-m', 'ziglang', 'cc', '-m32', '-target', 'x86-windows-gnu', '-O1', '-w',
                           '-fno-builtin', '-fwrapv', '-I', INCLUDE_DIR] + ['-I' + proj.file(i) for i in proj.include] +
                          [src, os.path.join(ROOT, 'tests', 'native_shim.c'), '-o', exe])
    return subprocess.run([exe], capture_output=True, text=True).stdout.splitlines()


def run_js(proj):
    r = subprocess.run(['node', os.path.join(ROOT, 'tests', 'run_js.js'), proj.dir], capture_output=True, text=True)
    if r.returncode:
        raise SystemExit('node failed:\n' + r.stderr)
    if r.stderr:
        print('   ', r.stderr.strip())
    return r.stdout.splitlines()


def test_project(path, native=True, verbose=False):
    proj, comp = build_project(path, quiet=True)
    js = run_js(proj)
    nat = run_native(proj) if native else None
    fails = 0
    for i, t in enumerate(proj.tests):
        name = '%s(%s)' % (t['call'], ', '.join(json.dumps(a) for a in t['args']))
        exp = expected_line(t)
        j = js[i] if i < len(js) else '<missing>'
        n = nat[i] if nat is not None and i < len(nat) else None
        ok = True
        if 'expect_error' in t:
            ok = j.startswith('E ') and t['expect_error'] in j
        else:
            ok = j == exp and (n is None or n == exp)
        if not ok:
            fails += 1
            print('  FAIL %s\n       expected %s\n       js       %s\n       native   %s' % (name, exp or 'error: ' + t['expect_error'], j, n))
        elif verbose:
            print('  ok   %s -> %s' % (name, j))
    print('%s %s: %d tests, %d failed' % ('PASS' if not fails else 'FAIL', proj.name, len(proj.tests), fails))
    return fails


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('-')]
    paths = [os.path.join(a, 'c2al.json') if os.path.isdir(a) else a for a in args] or \
        sorted(glob.glob(os.path.join(ROOT, 'examples', '*', 'c2al.json')))
    fails = sum(test_project(p, '--no-native' not in sys.argv, '-v' in sys.argv) for p in paths)
    sys.exit(1 if fails else 0)


if __name__ == '__main__':
    main()
